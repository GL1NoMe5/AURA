"""Measured acceptance harness for the SIM-001 cache worker.

Runs real cycles: healthy -> inject -> detect (RSS baseline + 24 MiB,
3 consecutive samples) -> reach 96 MiB ceiling and observe actually
rejected jobs -> restore -> independently verify 8 s -> shutdown.
Request load is synthetic (4 jobs/second, generated in-process); all
reported bytes/counters/times are measured, never fabricated.

Usage (from project root):
    backend\\.venv\\Scripts\\python.exe tools\\preflight\\worker_check.py
    backend\\.venv\\Scripts\\python.exe tools\\preflight\\worker_check.py --cycles 3
Evidence is written to .local/worker/last-run.json. Zero API requests.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import psutil

_REPO_ROOT = Path(__file__).resolve().parents[2]
_BACKEND = _REPO_ROOT / "backend"
if str(_BACKEND) not in sys.path:
    sys.path.insert(0, str(_BACKEND))

from aura_worker import WorkerController  # noqa: E402
from aura_worker.cache import CEILING_BYTES, HEALTHY_CACHE_BYTES  # noqa: E402
from aura_worker.controller import RSS_THRESHOLD_OFFSET_BYTES  # noqa: E402

DEFAULT_OUTPUT = _REPO_ROOT / ".local" / "worker" / "last-run.json"
REQUEST_LOAD_LABEL = (
    "synthetic request load: 4 in-process jobs/second generated by the "
    "worker scheduler; no external or provider requests"
)


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _pid_alive(pid: int | None) -> bool:
    if pid is None:
        return False
    try:
        return psutil.pid_exists(pid) and psutil.Process(pid).is_running()
    except (psutil.NoSuchProcess, psutil.AccessDenied, OSError):
        return False


def _surviving_owned(owned_tree: list[dict]) -> list[dict]:
    """Owned processes still alive, verified by PID + creation time.

    A PID whose current creation time differs was recycled by an unrelated
    process and is not counted (and never signalled).
    """
    surviving: list[dict] = []
    for identity in owned_tree or []:
        pid = identity.get("pid")
        if pid is None or not psutil.pid_exists(pid):
            continue
        try:
            proc = psutil.Process(pid)
            if abs(proc.create_time() - float(identity.get("create_time", -1))) > 0.01:
                continue
            if proc.is_running() and proc.status() != psutil.STATUS_ZOMBIE:
                surviving.append({"pid": pid,
                                  "create_time": identity.get("create_time")})
        except (psutil.NoSuchProcess, psutil.AccessDenied, OSError):
            continue
    return surviving


def evaluate_cycle(record: dict) -> dict:
    """Acceptance checks for one cycle; every prerequisite must hold."""
    baseline = record.get("baseline_rss_bytes")
    peak_rss = record.get("peak_rss_bytes")
    recovered_rss = record.get("recovered_rss_bytes")
    threshold = (
        baseline + RSS_THRESHOLD_OFFSET_BYTES if baseline is not None else None)
    v_start = record.get("verification_completed_start")
    v_end = record.get("verification_completed_end")
    f_start = record.get("verification_failed_start")
    f_end = record.get("verification_failed_end")
    return {
        "no_error": not record.get("error"),
        "fault_detected": record.get("fault_detected") is True,
        "ceiling_reached": (
            record.get("ceiling_reached") is True
            and record.get("peak_retained_cache_bytes") == CEILING_BYTES),
        "healthy_cache_exact": (
            record.get("healthy_retained_cache_bytes") == HEALTHY_CACHE_BYTES),
        "recovered_cache_exact": (
            record.get("recovered_retained_cache_bytes")
            == HEALTHY_CACHE_BYTES),
        "failed_jobs_positive": (
            (record.get("failed_jobs_at_ceiling") or 0) > 0),
        "rss_growth_beyond_threshold": (
            baseline is not None and peak_rss is not None
            and threshold is not None and peak_rss > threshold),
        "recovered_rss_within_threshold": (
            baseline is not None and recovered_rss is not None
            and threshold is not None and recovered_rss <= threshold),
        "recovery_verified": record.get("recovery_verified") is True,
        "verification_at_least_eight_seconds": (
            (record.get("verified_recovery_duration_seconds") or 0) >= 8.0),
        "verification_job_progress": (
            v_start is not None and v_end is not None and v_end > v_start),
        "no_new_failures_during_verification": (
            f_start is not None and f_end is not None and f_end == f_start),
        "owned_tree_cleanup": (
            bool(record.get("owned_tree"))
            and not record.get("surviving_owned_processes")
            and record.get("child_alive_after_shutdown") is False),
    }


def cycle_accepted(record: dict) -> bool:
    return all(evaluate_cycle(record).values())


async def _run_cycle(cycle_index: int) -> dict:
    controller = WorkerController()
    record: dict = {
        "cycle": cycle_index,
        "load_label": REQUEST_LOAD_LABEL,
        "api_requests_made": 0,
        "started_at": _utc_now(),
    }
    pid: int | None = None
    try:
        healthy = await asyncio.wait_for(controller.start(), timeout=30)
        pid = controller.child_pid
        record["child_pid"] = pid
        record["baseline_rss_bytes"] = controller.baseline_rss_bytes
        record["healthy_retained_cache_bytes"] = healthy.get(
            "retained_cache_bytes")
        record["healthy_completed_jobs"] = healthy.get("completed_jobs")

        inject_started = time.monotonic()
        await controller.inject_cache_retention()
        detected = await controller.wait_for_detection(timeout=30)
        record["fault_detected"] = detected
        record["detected_at"] = controller.detected_at
        record["detection_seconds"] = round(
            time.monotonic() - inject_started, 3)

        deadline = time.monotonic() + 60
        status = healthy
        while time.monotonic() < deadline:
            status = await controller.status()
            if (status.get("retained_cache_bytes") == CEILING_BYTES
                    and (status.get("failed_jobs") or 0) > 0):
                break
            await asyncio.sleep(0.25)
        if (status.get("retained_cache_bytes") == CEILING_BYTES
                and (status.get("failed_jobs") or 0) > 0):
            # Observe rejected jobs at the ceiling for two more seconds so
            # the recorded failure counter reflects sustained rejection.
            await asyncio.sleep(2.0)
            status = await controller.status()
        record["ceiling_reached"] = (
            status.get("retained_cache_bytes") == CEILING_BYTES)
        record["peak_retained_cache_bytes"] = status.get(
            "retained_cache_bytes")
        record["failed_jobs_at_ceiling"] = status.get("failed_jobs")
        record["completed_jobs_at_ceiling"] = status.get("completed_jobs")
        record["time_to_ceiling_seconds"] = round(
            time.monotonic() - inject_started, 3)
        record["peak_rss_bytes"] = controller.peak_rss_bytes

        result = await controller.restore_and_verify(timeout=40)
        record["recovery_verified"] = result.verified
        record["recovery_reason"] = result.reason
        record["verified_recovery_duration_seconds"] = round(
            result.duration_seconds, 3)
        record["verification_completed_start"] = result.completed_jobs_start
        record["verification_completed_end"] = result.completed_jobs
        record["verification_failed_start"] = result.failed_jobs_start
        record["verification_failed_end"] = result.failed_jobs
        record["recovered_rss_bytes"] = (
            controller.fresh_rss_bytes or controller.latest_rss_bytes)
        after = await controller.status()
        record["recovered_retained_cache_bytes"] = after.get(
            "retained_cache_bytes")
        record["recovered_completed_jobs"] = after.get("completed_jobs")
        record["recovered_failed_jobs"] = after.get("failed_jobs")
        record["rss_threshold_bytes"] = (
            (controller.baseline_rss_bytes or 0)
            + RSS_THRESHOLD_OFFSET_BYTES)
        record["controller_state"] = controller.state.value
        record["measurements"] = controller.snapshot()["measurements"]
        record["state_history"] = controller.snapshot()["state_history"]
    except Exception as exc:  # honest failure record, harness continues
        record["error"] = f"{type(exc).__name__}: {exc}"[:512]
        record["recovery_verified"] = False
    finally:
        record["owned_tree"] = controller.owned_process_identities
        record["generation"] = controller.generation
        await controller.stop()
        record["child_alive_after_shutdown"] = _pid_alive(pid)
        record["surviving_owned_processes"] = _surviving_owned(
            record["owned_tree"])
        record["finished_at"] = _utc_now()
    record["expected_healthy_cache_bytes"] = HEALTHY_CACHE_BYTES
    record["expected_ceiling_bytes"] = CEILING_BYTES
    record["checks"] = evaluate_cycle(record)
    record["accepted"] = all(record["checks"].values())
    return record


async def _run(cycles: int) -> dict:
    started = _utc_now()
    records = [await _run_cycle(i + 1) for i in range(cycles)]
    return {
        "tool": "tools/preflight/worker_check.py",
        "task": "SIM-001-R1",
        "started_at": started,
        "finished_at": _utc_now(),
        "cycles_requested": cycles,
        "request_load": REQUEST_LOAD_LABEL,
        "api_requests_made": 0,
        "all_cycles_verified": bool(records) and all(
            cycle_accepted(r) for r in records),
        "cycles": records,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cycles", type=int, default=1,
                        help="number of full fault/recovery cycles (default 1)")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    if args.cycles < 1:
        parser.error("--cycles must be >= 1")
    report = asyncio.run(_run(args.cycles))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2), encoding="utf-8")
    for record in report["cycles"]:
        print(
            f"cycle {record['cycle']}: baseline={record.get('baseline_rss_bytes')} "
            f"peak_rss={record.get('peak_rss_bytes')} "
            f"recovered_rss={record.get('recovered_rss_bytes')} "
            f"peak_cache={record.get('peak_retained_cache_bytes')} "
            f"failed={record.get('failed_jobs_at_ceiling')} "
            f"verified={record.get('recovery_verified')} "
            f"child_alive_after={record.get('child_alive_after_shutdown')}")
    print(f"evidence: {args.output}")
    return 0 if report["all_cycles_verified"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
